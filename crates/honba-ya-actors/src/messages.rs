//! Message contracts and types for actor communications.

use chrono::{DateTime, Utc};
use honba_core::{Bar, FillReport, InstrumentId, OrderAck, OrderRequest, OrderStatus, Tick};
use honba_te_core::BrokerError;
use tokio::sync::oneshot;

/// Lifecycle status of an individual actor or the entire runtime.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ActorStatus {
    /// Actor is initializing and establishing connections.
    Starting,
    /// Actor is active and processing messages normally.
    Running,
    /// Actor is draining remaining queued messages or orders prior to stopping.
    Draining,
    /// Actor has terminated gracefully.
    Stopped,
    /// Actor encountered a fatal error.
    Errored(String),
}

/// Commands and events dispatched to the `MarketDataActor`.
#[derive(Debug)]
pub enum MarketDataMsg {
    /// Ingest an inbound tick from an external broker or feed stream.
    IngestTick(Tick),
    /// Ingest an aggregated OHLCV bar.
    IngestBar(Bar),
    /// Subscribe an instrument.
    Subscribe(InstrumentId),
    /// Unsubscribe an instrument.
    Unsubscribe(InstrumentId),
    /// Request actor shutdown.
    Shutdown,
}

/// Commands and events dispatched to the `StrategyActor`.
#[derive(Debug)]
pub enum StrategyMsg {
    /// Inbound market tick for evaluation.
    OnTick(Tick),
    /// Inbound bar for evaluation.
    OnBar(Bar),
    /// Inbound fill notification.
    OnFill(FillReport),
    /// Request actor shutdown.
    Shutdown,
}

/// Commands and queries dispatched to the `RiskActor`.
#[derive(Debug)]
pub enum RiskMsg {
    /// Evaluate a candidate order request against pre-trade risk controls.
    /// If approved, the RiskActor forwards to ExecutionActor and returns the ack.
    EvaluateOrder {
        /// Order candidate generated by strategy
        request: OrderRequest,
        /// Evaluation timestamp
        now: DateTime<Utc>,
        /// Channel to return execution result or pre-trade refusal
        reply_to: oneshot::Sender<Result<OrderAck, BrokerError>>,
    },
    /// Record an order cancellation in the risk engine for OTR tracking.
    RecordCancellation {
        /// Exchange-registered algo ID
        algo_id: String,
    },
    /// Record an execution fill report in the risk engine.
    RecordFill(FillReport),
    /// Trigger an emergency per-algo halt.
    HaltAlgo {
        /// Algo ID to halt
        algo_id: String,
        /// Reason for halt
        reason: String,
    },
    /// Resume an algo previously halted.
    ResumeAlgo {
        /// Algo ID to resume
        algo_id: String,
    },
    /// Trigger platform-wide emergency kill switch.
    HaltGlobal {
        /// Reason for kill switch
        reason: String,
    },
    /// Resume platform-wide trading.
    ResumeGlobal,
    /// Request actor shutdown.
    Shutdown,
}

/// Commands and queries dispatched to the `ExecutionActor`.
#[derive(Debug)]
pub enum ExecutionMsg {
    /// Dispatch an approved order directly to the broker adapter.
    ExecuteOrder {
        /// Risk-approved order request
        request: OrderRequest,
        /// Channel returning broker acknowledgement or broker failure
        reply_to: oneshot::Sender<Result<OrderAck, BrokerError>>,
    },
    /// Cancel an active order by broker order ID.
    CancelOrder {
        /// Broker order ID
        order_id: String,
        /// Algo ID for tracking
        algo_id: String,
        /// Channel returning cancellation result
        reply_to: oneshot::Sender<Result<(), BrokerError>>,
    },
    /// Query order status from broker.
    QueryStatus {
        /// Broker order ID
        order_id: String,
        /// Channel returning order status
        reply_to: oneshot::Sender<Result<OrderStatus, BrokerError>>,
    },
    /// Request actor shutdown.
    Shutdown,
}
