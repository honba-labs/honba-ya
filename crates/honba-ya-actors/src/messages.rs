//! Message contracts and types for actor communications.

use chrono::{DateTime, Utc};
use honba_core::{
    Bar, FillReport, InstrumentId, Money, OrderAck, OrderRequest, OrderStatus, Price, Quantity,
    Tick,
};
use honba_portfolio::CorporateAction;
use honba_portfolio::TaxSummary;
use rust_decimal::Decimal;
use tokio::sync::oneshot;

/// Re-export honba_te_core::BrokerError for actor communication.
pub use honba_te_core::BrokerError;

/// Lifecycle status of an individual actor or the entire runtime.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ActorStatus {
    /// Actor is initializing and establishing connections.
    Starting,
    /// Actor is active and processing messages normally.
    Running,
    /// Actor execution is degraded (e.g. Python task timeout / fail-safe active).
    Degraded,
    /// Actor is draining remaining queued messages or orders prior to stopping.
    Draining,
    /// Actor has terminated gracefully.
    Stopped,
    /// Actor encountered a fatal error.
    Errored(String),
}

/// Commands and events dispatched to the `MarketDataActor`.
#[derive(Debug)]
pub enum MarketDataMsg {
    /// Ingest an inbound tick from an external broker or feed stream.
    IngestTick(Tick),
    /// Ingest an aggregated OHLCV bar.
    IngestBar(Bar),
    /// Subscribe an instrument.
    Subscribe(InstrumentId),
    /// Unsubscribe an instrument.
    Unsubscribe(InstrumentId),
    /// Request actor shutdown.
    Shutdown,
}

/// Commands and events dispatched to the `StrategyActor`.
#[derive(Debug)]
pub enum StrategyMsg {
    /// Inbound market tick for evaluation.
    OnTick(Tick),
    /// Inbound bar for evaluation.
    OnBar(Bar),
    /// Inbound fill notification.
    OnFill(FillReport),
    /// Request actor shutdown.
    Shutdown,
}

/// Commands and queries dispatched to the `PositionSizingActor`.
#[derive(Debug)]
pub enum PositionSizingMsg {
    /// Ingest a candidate order from StrategyActor, compute dynamic position sizing,
    /// and forward the sized request to RiskActor.
    SizeOrder {
        /// Candidate order request from strategy
        request: OrderRequest,
        /// Evaluation timestamp
        now: DateTime<Utc>,
        /// Channel returning broker acknowledgement or pre-trade refusal
        reply_to: oneshot::Sender<Result<OrderAck, BrokerError>>,
    },
    /// Update the current instantaneous portfolio state for risk budget evaluation.
    UpdatePortfolio(honba_kokoro::sizing::Portfolio),
    /// Set dynamic position sizing method.
    SetSizingMethod(honba_core::sizing::SizingMethod),
    /// Set default risk percentage per trade.
    SetRiskPct(Decimal),
    /// Request actor shutdown.
    Shutdown,
}

/// Commands and queries dispatched to the `RiskActor`.
#[derive(Debug)]
pub enum RiskMsg {
    /// Evaluate a candidate order request against pre-trade risk controls.
    /// If approved, the RiskActor forwards to ExecutionActor and returns the ack.
    EvaluateOrder {
        /// Order candidate generated by strategy
        request: OrderRequest,
        /// Evaluation timestamp
        now: DateTime<Utc>,
        /// Channel to return execution result or pre-trade refusal
        reply_to: oneshot::Sender<Result<OrderAck, BrokerError>>,
    },
    /// Record an order cancellation in the risk engine for OTR tracking.
    RecordCancellation {
        /// Exchange-registered algo ID
        algo_id: String,
    },
    /// Record an execution fill report in the risk engine.
    RecordFill(FillReport),
    /// Trigger an emergency per-algo halt.
    HaltAlgo {
        /// Algo ID to halt
        algo_id: String,
        /// Reason for halt
        reason: String,
    },
    /// Resume an algo previously halted.
    ResumeAlgo {
        /// Algo ID to resume
        algo_id: String,
    },
    /// Trigger platform-wide emergency kill switch.
    HaltGlobal {
        /// Reason for kill switch
        reason: String,
    },
    /// Resume platform-wide trading.
    ResumeGlobal,
    /// Request actor shutdown.
    Shutdown,
}

/// Structured risk breach event emitted for persistence audit stream.
///
/// Emitted synchronously when `RiskEngine` refuses an order, providing
/// an immutable record for SEBI regulatory audit and post-trade analysis.
#[derive(Debug, Clone)]
pub struct RiskBreachEvent {
    /// Timestamp of the breach
    pub ts: DateTime<Utc>,
    /// Algo ID associated with the breach
    pub algo_id: String,
    /// Instrument being traded
    pub instrument: InstrumentId,
    /// Refusal reason from the risk engine
    pub refusal_reason: String,
    /// Regulatory rule code (e.g., "freeze_limit_exceeded", "price_band_violation")
    pub rule_code: &'static str,
    /// Evaluation latency in microseconds
    pub eval_duration_us: u64,
    /// Requested order quantity
    pub requested_qty: Option<Quantity>,
    /// Requested order price limit
    pub requested_price: Option<Price>,
}

/// Commands and queries dispatched to the `ExecutionActor`.
#[derive(Debug)]
pub enum ExecutionMsg {
    /// Dispatch an approved order directly to the broker adapter.
    ExecuteOrder {
        /// Risk-approved order request
        request: OrderRequest,
        /// Channel returning broker acknowledgement or broker failure
        reply_to: oneshot::Sender<Result<OrderAck, BrokerError>>,
    },
    /// Cancel an active order by broker order ID.
    CancelOrder {
        /// Broker order ID
        order_id: String,
        /// Algo ID for tracking
        algo_id: String,
        /// Channel returning cancellation result
        reply_to: oneshot::Sender<Result<(), BrokerError>>,
    },
    /// Query order status from broker.
    QueryStatus {
        /// Broker order ID
        order_id: String,
        /// Channel returning order status
        reply_to: oneshot::Sender<Result<OrderStatus, BrokerError>>,
    },
    /// Risk breach event emitted from RiskActor for audit stream persistence.
    RiskBreachEvent(RiskBreachEvent),
    /// Request actor shutdown.
    Shutdown,
}

/// Commands and queries dispatched to the `PortfolioActor`.
#[derive(Debug)]
pub enum PortfolioMsg {
    /// Process a fill report from the execution layer.
    ProcessFill {
        fill: FillReport,
        reply_to: oneshot::Sender<Result<PortfolioUpdate, PortfolioError>>,
    },
    /// Get current portfolio snapshot.
    GetSnapshot {
        reply_to: oneshot::Sender<PortfolioSnapshot>,
    },
    /// Get tax summary for a period.
    GetTaxSummary {
        period_start: chrono::NaiveDate,
        period_end: chrono::NaiveDate,
        reply_to: oneshot::Sender<TaxSummary>,
    },
    /// Apply corporate actions.
    ApplyCorporateActions {
        actions: Vec<CorporateAction>,
        reply_to: oneshot::Sender<()>,
    },
    /// Perform T+1 settlement for a date.
    SettleTrades {
        current_date: chrono::NaiveDate,
        reply_to: oneshot::Sender<PortfolioSettleResult>,
    },
    /// Request actor shutdown.
    Shutdown,
}

/// Result of processing a fill in the portfolio.
#[derive(Debug, Clone)]
pub struct PortfolioUpdate {
    /// Updated positions after the fill
    pub positions: std::collections::BTreeMap<String, Vec<honba_portfolio::HeldPosition>>,
    /// Realized PnL from this fill
    pub realized_pnl: Money,
    /// Updated cash balance
    pub cash: Money,
    /// Any tax/fee breakdown
    pub fees: FeeBreakdown,
}

/// Fee breakdown for a fill.
#[derive(Debug, Clone)]
pub struct FeeBreakdown {
    pub stt: Money,
    pub gst: Money,
    pub stamp_duty: Money,
    pub sebi_turnover: Money,
    pub dp_charges: Money,
    pub brokerage: Money,
}

impl Default for FeeBreakdown {
    fn default() -> Self {
        Self {
            stt: Money::inr(Decimal::ZERO),
            gst: Money::inr(Decimal::ZERO),
            stamp_duty: Money::inr(Decimal::ZERO),
            sebi_turnover: Money::inr(Decimal::ZERO),
            dp_charges: Money::inr(Decimal::ZERO),
            brokerage: Money::inr(Decimal::ZERO),
        }
    }
}

/// Portfolio snapshot for reporting.
#[derive(Debug, Clone)]
pub struct PortfolioSnapshot {
    pub total_equity: Money,
    pub cash: Money,
    pub unrealized_pnl: Money,
    pub realized_pnl: Money,
    pub positions: std::collections::BTreeMap<String, Vec<honba_portfolio::HeldPosition>>,
}

/// Errors from the PortfolioActor.
#[derive(Debug, thiserror::Error)]
pub enum PortfolioError {
    #[error("Instrument not found in portfolio: {0}")]
    InstrumentNotFound(String),
    #[error("Insufficient position for sell: {0}")]
    InsufficientPosition(String),
    #[error("Ledger error: {0}")]
    LedgerError(String),
    #[error("Tax calculation error: {0}")]
    TaxError(String),
    #[error("Internal error: {0}")]
    Internal(String),
}

/// Settlement result for portfolio.
#[derive(Debug, Clone)]
pub struct PortfolioSettleResult {
    pub settled_count: usize,
    pub failed_count: usize,
    pub cash_flow: Money,
    pub securities_moved: Vec<InstrumentId>,
    pub errors: Vec<String>,
}

impl PortfolioSettleResult {
    pub fn is_successful(&self) -> bool {
        self.failed_count == 0
    }
}
