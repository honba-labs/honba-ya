//! Pure event-driven backtesting engine enforcing research-live parity.
//!
//! Reuses the identical [`Strategy`] trait from `honba-ya-actors` and [`RiskEngine`]
//! from `honba-mon` in simulation as in live trading, with exact Indian cost modeling
//! and T+1 rolling settlement.

use chrono::{DateTime, NaiveDate, Utc};
use rust_decimal::Decimal;
use rust_decimal_macros::dec;
use std::collections::{HashMap, HashSet};
use uuid::Uuid;

use honba_actors::Strategy;
use honba_core::{FillReport, InstrumentId, OrderRequest, OrderSide, OrderType, Price};
use honba_mon::RiskEngine;

use crate::calendar::NseTradingCalendar;
use crate::costs::{IndianCostModel, IndianFeeBreakdown, ProductType};
use crate::events::{MarketEvent, OrderEvent, SignalEvent};
use crate::settlement::SettlementLedger;

/// Configuration for backtest execution.
#[derive(Debug, Clone)]
pub struct BacktestConfig {
    /// Initial starting capital in INR
    pub starting_cash: Decimal,
    /// Product type (Delivery vs Intraday)
    pub product_type: ProductType,
}

impl Default for BacktestConfig {
    fn default() -> Self {
        Self {
            starting_cash: dec!(1_000_000.00), // ₹10 Lakhs
            product_type: ProductType::Delivery,
        }
    }
}

/// Comprehensive performance and regulatory audit results of a backtest run.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct BacktestResult {
    /// Initial capital in INR
    pub initial_cash: Decimal,
    /// Final equity (settled cash + mark-to-market securities)
    pub final_equity: Decimal,
    /// Net PnL after all Indian statutory taxes and transaction fees
    pub net_pnl: Decimal,
    /// Gross trading PnL before fees
    pub gross_pnl: Decimal,
    /// Detailed itemized Indian statutory fee breakdown
    pub total_fees: IndianFeeBreakdown,
    /// Total executed trades / fills
    pub total_trades: usize,
    /// Total candidate orders generated by strategy
    pub total_signals: usize,
    /// Number of orders refused by the pre-trade `RiskEngine`
    pub refused_orders: usize,
    /// Maximum portfolio drawdown percentage (e.g. 5.25 for 5.25%)
    pub max_drawdown_pct: Decimal,
}

/// Event-driven backtester core engine.
pub struct BacktestEngine<S: Strategy> {
    strategy: S,
    risk_engine: RiskEngine,
    cost_model: IndianCostModel,
    calendar: NseTradingCalendar,
    ledger: SettlementLedger,
    product_type: ProductType,

    latest_prices: HashMap<InstrumentId, Price>,
    scrips_sold_today: HashSet<InstrumentId>,
    current_date: Option<NaiveDate>,

    // Performance tracking
    initial_cash: Decimal,
    total_signals: usize,
    refused_orders: usize,
    total_trades: usize,
    gross_pnl: Decimal,
    total_fees: IndianFeeBreakdown,
    peak_equity: Decimal,
    max_drawdown: Decimal,
}

impl<S: Strategy> BacktestEngine<S> {
    /// Create a new backtest engine with injected strategy and risk engine.
    pub fn new(
        strategy: S,
        risk_engine: RiskEngine,
        config: BacktestConfig,
        cost_model: IndianCostModel,
        calendar: NseTradingCalendar,
    ) -> Self {
        let initial_cash = config.starting_cash;
        Self {
            strategy,
            risk_engine,
            cost_model,
            calendar,
            ledger: SettlementLedger::new(initial_cash),
            product_type: config.product_type,
            latest_prices: HashMap::new(),
            scrips_sold_today: HashSet::new(),
            current_date: None,
            initial_cash,
            total_signals: 0,
            refused_orders: 0,
            total_trades: 0,
            gross_pnl: Decimal::ZERO,
            total_fees: IndianFeeBreakdown::default(),
            peak_equity: initial_cash,
            max_drawdown: Decimal::ZERO,
        }
    }

    /// Process a stream of chronological market events through the complete event loop:
    /// $$\text{MarketEvent} \longrightarrow \text{SignalEvent} \longrightarrow \text{OrderEvent} \longrightarrow \text{FillEvent}$$
    pub async fn run_events<I>(&mut self, events: I) -> BacktestResult
    where
        I: IntoIterator<Item = MarketEvent>,
    {
        for event in events {
            self.process_market_event(event).await;
        }

        // Final settlement flush to current date
        if let Some(date) = self.current_date {
            let next_day = self.calendar.next_trading_day(date);
            self.ledger.settle_up_to(next_day);
        }

        let final_equity = self.current_equity();
        let net_pnl = final_equity - self.initial_cash;

        let max_drawdown_pct = if self.peak_equity > Decimal::ZERO {
            (self.max_drawdown / self.peak_equity * dec!(100.00)).round_dp(2)
        } else {
            Decimal::ZERO
        };

        BacktestResult {
            initial_cash: self.initial_cash,
            final_equity,
            net_pnl,
            gross_pnl: self.gross_pnl,
            total_fees: self.total_fees.clone(),
            total_trades: self.total_trades,
            total_signals: self.total_signals,
            refused_orders: self.refused_orders,
            max_drawdown_pct,
        }
    }

    async fn process_market_event(&mut self, event: MarketEvent) {
        let ts = event.timestamp();
        let event_date = ts.date_naive();

        // 1. Check Date Advance for T+1 Settlement & DP charge reset
        if self.current_date != Some(event_date) {
            self.current_date = Some(event_date);
            self.scrips_sold_today.clear();
            self.ledger.settle_up_to(event_date);
        }

        // 2. Update price cache
        match &event {
            MarketEvent::Tick(t) => {
                if let Some(p) = t.last_price() {
                    self.latest_prices.insert(t.instrument().clone(), p);
                }
            }
            MarketEvent::Bar(b) => {
                self.latest_prices.insert(b.instrument.clone(), b.close);
            }
        }

        // 3. MarketEvent -> SignalEvent (Strategy Invocation)
        let candidate_orders = match &event {
            MarketEvent::Tick(t) => self.strategy.on_tick(t).await,
            MarketEvent::Bar(b) => self.strategy.on_bar(b).await,
        };

        if candidate_orders.is_empty() {
            self.update_drawdown();
            return;
        }

        self.total_signals += candidate_orders.len();
        let signal_event = SignalEvent {
            orders: candidate_orders,
            timestamp: ts,
            algo_id: self.strategy.algo_id().to_string(),
        };

        // 4. SignalEvent -> OrderEvent (Synchronous RiskEngine Pre-Trade Gate)
        for order in signal_event.orders {
            let order_event = match self.risk_engine.check_order(&order, ts) {
                Ok(()) => OrderEvent::Approved(order),
                Err(reason) => {
                    self.refused_orders += 1;
                    OrderEvent::Refused { order, reason }
                }
            };

            // 5. OrderEvent -> FillEvent (Execution Simulation with Indian Cost Model)
            if let OrderEvent::Approved(approved_order) = order_event {
                self.simulate_execution(approved_order, ts).await;
            }
        }

        self.update_drawdown();
    }

    async fn simulate_execution(&mut self, order: OrderRequest, timestamp: DateTime<Utc>) {
        let instrument = &order.instrument;
        let current_price = match self.latest_prices.get(instrument) {
            Some(p) => *p,
            None => return, // No market price available yet to match
        };

        // Check limit price matching condition
        let fill_price = match order.order_type {
            OrderType::Market => current_price,
            OrderType::Limit(limit) => {
                match order.side {
                    OrderSide::Buy => {
                        if limit >= current_price {
                            current_price // Price improvement to market
                        } else {
                            return; // Limit buy below market not filled
                        }
                    }
                    OrderSide::Sell => {
                        if limit <= current_price {
                            current_price
                        } else {
                            return; // Limit sell above market not filled
                        }
                    }
                }
            }
            _ => current_price,
        };

        let notional = fill_price.0 * order.quantity.0;
        let is_first_sell = if order.side == OrderSide::Sell {
            self.scrips_sold_today.insert(instrument.clone())
        } else {
            false
        };

        // Compute exact statutory taxes & brokerage
        let fees =
            self.cost_model
                .compute_fees(order.side, self.product_type, notional, is_first_sell);
        self.total_fees.add_assign(&fees);

        let trade_date = timestamp.date_naive();
        let fill_id = Uuid::new_v4().to_string();

        let fill_report = FillReport {
            fill_id,
            order_id: Uuid::new_v4().to_string(),
            client_order_id: order.client_order_id,
            instrument: order.instrument.clone(),
            side: order.side,
            price: fill_price,
            quantity: order.quantity,
            algo_id: order.algo_id.clone(),
            timestamp,
        };

        // Update Research-Live Parity: notify RiskEngine & Strategy
        self.risk_engine.record_fill(&fill_report);
        self.strategy.on_fill(&fill_report).await;

        // Apply T+1 settlement or cash update
        match order.side {
            OrderSide::Buy => {
                let total_debit = notional + fees.total();
                self.gross_pnl -= Decimal::ZERO; // buy establishes cost basis
                self.ledger.record_delivery_buy(
                    order.instrument,
                    order.quantity,
                    total_debit,
                    trade_date,
                    &self.calendar,
                );
            }
            OrderSide::Sell => {
                let net_credit = notional - fees.total();
                self.gross_pnl += notional;
                self.ledger.record_delivery_sell(
                    order.instrument,
                    order.quantity,
                    net_credit,
                    trade_date,
                    &self.calendar,
                );
            }
        }

        self.total_trades += 1;
    }

    fn current_equity(&self) -> Decimal {
        self.ledger.total_equity(|inst| {
            self.latest_prices
                .get(inst)
                .map(|p| p.0)
                .unwrap_or(Decimal::ZERO)
        })
    }

    fn update_drawdown(&mut self) {
        let equity = self.current_equity();
        if equity > self.peak_equity {
            self.peak_equity = equity;
        }
        let drawdown = self.peak_equity - equity;
        if drawdown > self.max_drawdown {
            self.max_drawdown = drawdown;
        }
    }
}
