//! Event-driven backtester event definitions.
//!
//! Enforces the canonical research-live parity event chain:
//! $$\text{MarketEvent} \longrightarrow \text{SignalEvent} \longrightarrow \text{OrderEvent} \longrightarrow \text{FillEvent}$$

use chrono::{DateTime, Utc};
use rust_decimal::Decimal;
use serde::{Deserialize, Serialize};

use honba_core::{Bar, FillReport, OrderRequest, Tick};
use honba_mon::RiskRefusal;

use honba_kokoro_ledger::TaxBreakdown;

/// Market event entering the event loop (ticks or historical bars).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum MarketEvent {
    /// Inbound tick
    Tick(Tick),
    /// Inbound aggregated OHLCV bar
    Bar(Bar),
}

impl MarketEvent {
    /// Extract event timestamp in UTC.
    pub fn timestamp(&self) -> DateTime<Utc> {
        match self {
            Self::Tick(t) => t.receive_ts(),
            Self::Bar(b) => b.timestamp,
        }
    }

    /// Converts this backtest-local event into the canonical
    /// `honba_core::MarketEvent` the strategy layer (`StrategyRunner`)
    /// consumes. Pure and total: the backtest engine never produces a
    /// `ConnectorStateChanged` event, so this mapping only ever needs the
    /// two leaf variants both enums share.
    pub fn to_core_event(&self) -> honba_core::MarketEvent {
        match self {
            Self::Tick(t) => honba_core::MarketEvent::Tick(t.clone()),
            Self::Bar(b) => honba_core::MarketEvent::Bar(b.clone()),
        }
    }
}

/// Candidate trading signal generated by a strategy.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SignalEvent {
    /// Candidate orders generated by the strategy
    pub orders: Vec<OrderRequest>,
    /// Generation timestamp
    pub timestamp: DateTime<Utc>,
    /// Algorithm identifier
    pub algo_id: String,
}

/// Order evaluation event evaluated by the synchronous pre-trade `RiskEngine`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum OrderEvent {
    /// Order successfully cleared all pre-trade risk controls and circuit limits
    Approved(OrderRequest),
    /// Order was rejected by the risk gate
    Refused {
        /// Rejected order
        order: OrderRequest,
        /// Reason for risk gate rejection
        reason: RiskRefusal,
    },
}

/// Simulated trade fill event matching against market depth/ticks with Indian cost modeling.
#[derive(Debug, Clone, PartialEq)]
pub struct FillEvent {
    /// Canonical fill report
    pub fill_report: FillReport,
    /// Exact statutory fees calculated for this fill
    pub fees: TaxBreakdown,
    /// Net cash impact of this fill
    pub net_cash: Decimal,
    /// Execution timestamp
    pub timestamp: DateTime<Utc>,
}
